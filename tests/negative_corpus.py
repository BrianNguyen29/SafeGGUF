# Advisory placeholder registry: manifest-only entries for advisories whose
# primary-source provenance has not been triaged yet. Each entry would carry a
# mechanism and the expected SafeGGUF protection path, but no fixture file and
# no verified assertion; all provenance fields stay "TRIAGE-PENDING" (never
# invent tracker URLs, advisory links or commit SHAs). Promote an entry into
# CASES - and only then generate a cve-<id>-<mechanism>.gguf fixture - once
# cve, ghsa, source_url and a patched reference are recorded from a
# verifiable primary source. CVE-2025-53630, CVE-2026-27940 and CVE-2026-33298
# were promoted into CASES with triaged provenance (B3), so the registry is
# empty today; it stays available for future advisories.
ADVISORY_PLACEHOLDERS = []


# Shared schema every CASES entry must define. Provenance fields are
# nullable and stay present with a null value where nothing was verified
# (null = unknown): affected_range/affected_version/patched_version/
# patched_commit may be null individually; a cve-* case must still record at
# least one patched reference.
CASE_FIELDS = (
    "name",
    "fixture_type",
    "bug_class",
    "build",
    "source",
    "source_url",
    "affected_range",
    "affected_version",
    "patched_version",
    "patched_commit",
    "expected_behavior",
    "expected_error_code",
    "cli_args",
)

# Fields a promoted cve-* case must populate with a triaged (non-null,
# non-TRIAGE-PENDING) value: advisory identity (fixture category, closed
# fixture_origin, cve, ghsa), verifiable primary source_url, fixture sha256
# and the expected profile/error the rejection is asserted under. Version
# ranges/commits stay schema-nullable (see CASE_FIELDS). Synthetic cases
# legitimately carry null provenance (no advisory exists) and
# ADVISORY_PLACEHOLDERS stay manifest-only with TRIAGE-PENDING fields; only
# cve-* entries in CASES are held to triaged values for every field here.
REQUIRED_CVE_FIELDS = (
    "fixture_type",
    "fixture_origin",
    "cve",
    "ghsa",
    "source_url",
    "sha256",
    "expected_profile",
    "expected_error_code",
)


def _case_profile(case):
    """Effective --profile of a case (the CLI default when cli_args omit it)."""
    args = case["cli_args"]
    if "--profile" not in args:
        return "gguf-spec"
    index = args.index("--profile")
    if index + 1 >= len(args):
        return None  # dangling --profile: reported as an unknown profile
    return args[index + 1]


def _require_case_schema(case):
    """Enforce the shared case schema: known fields, all present, valid profile."""
    name = case.get("name", "<unnamed>")
    unknown = sorted(set(case) - set(CASE_FIELDS) - set(REQUIRED_CVE_FIELDS))
    if unknown:
        raise SystemExit(
            f"provenance error: {name} carries fields outside the provenance "
            f"schema: {', '.join(unknown)}"
        )
    missing = [field for field in CASE_FIELDS if field not in case]
    if missing:
        raise SystemExit(
            f"provenance error: {name} is missing schema fields: "
            f"{', '.join(missing)}"
        )
    profile = _case_profile(case)
    if profile not in PROFILES:
        raise SystemExit(
            f"provenance error: {name} uses unknown profile {profile!r} in "
            f"cli_args; expected one of {' | '.join(PROFILES)}"
        )


def _require_cve_provenance(case):
    """Enforce the full promoted cve-* provenance schema on one case."""
    name = case["name"]
    missing = [
        field
        for field in REQUIRED_CVE_FIELDS
        if not case.get(field) or case.get(field) == "TRIAGE-PENDING"
    ]
    if missing:
        raise SystemExit(
            f"provenance error: {name} claims a CVE identity without "
            f"triaged {', '.join(missing)}"
        )
    if case["fixture_type"] != "advisory-regression":
        raise SystemExit(
            f"provenance error: {name} claims a CVE identity with "
            f"fixture_type {case['fixture_type']!r} (must be "
            "'advisory-regression')"
        )
    if case["fixture_origin"] not in FIXTURE_ORIGINS:
        raise SystemExit(
            f"provenance error: {name} has fixture_origin "
            f"{case['fixture_origin']!r} outside the closed vocabulary: "
            f"{' | '.join(FIXTURE_ORIGINS)}"
        )
    if not CVE_ID_RE.match(case["cve"]):
        raise SystemExit(
            f"provenance error: {name} has malformed cve {case['cve']!r}"
        )
    if case["cve"].lower() not in name:
        raise SystemExit(
            f"provenance error: {name} cve {case['cve']} does not match the "
            "fixture name"
        )
    if not GHSA_ID_RE.match(case["ghsa"]):
        raise SystemExit(
            f"provenance error: {name} has malformed ghsa {case['ghsa']!r}"
        )
    if not case["source_url"].startswith("https://"):
        raise SystemExit(
            f"provenance error: {name} source_url is not an https URL: "
            f"{case['source_url']!r}"
        )
    if not SHA256_RE.match(case["sha256"]):
        raise SystemExit(
            f"provenance error: {name} has malformed sha256 {case['sha256']!r}"
        )
    if not (case["patched_commit"] or case["patched_version"]):
        raise SystemExit(
            f"provenance error: {name} records no patched reference "
            "(patched_commit and patched_version are both null)"
        )
    if case["expected_profile"] != _case_profile(case):
        raise SystemExit(
            f"provenance error: {name} expected_profile "
            f"{case['expected_profile']!r} does not match the cli_args profile "
            f"{_case_profile(case)!r}"
        )
    if not case["expected_error_code"].startswith("E_"):
        raise SystemExit(
            f"provenance error: {name} has malformed expected_error_code "
            f"{case['expected_error_code']!r}"
        )


def _require_triaged_provenance():
    """A cve-* fixture may only exist once its advisory provenance is triaged.

    Enforces the corpus invariant mechanically: every case fills the shared
    schema (nullable provenance fields stay present and null where unknown),
    synthetic fixtures must not borrow an advisory identity, and a cve-* case
    must satisfy the full provenance schema - triaged advisory identity,
    primary source, fixture hash, expected profile/error and a patched
    reference - with fixture_origin drawn from the closed vocabulary.
    """
    for case in CASES:
        _require_case_schema(case)
        if case["name"].startswith("cve-"):
            _require_cve_provenance(case)


def generate():
    """Deterministically write all fixtures and the manifest; prune stale files."""
    _require_triaged_provenance()
    os.makedirs(NEGATIVE_DIR, exist_ok=True)

    manifest_cases = []
    for case in CASES:
        payload = case["build"]()
        digest = hashlib.sha256(payload).hexdigest()
        declared = case.get("sha256")
        if declared is not None and declared != digest:
            raise SystemExit(
                f"provenance error: {case['name']} declares sha256 {declared} "
                f"but the generated payload hashes to {digest}"
            )
        path = os.path.join(NEGATIVE_DIR, case["name"])
        with open(path, "wb") as f:
            f.write(payload)
        manifest_cases.append(
            {
                "file": case["name"],
                "fixture_type": case["fixture_type"],
                "fixture_origin": case.get("fixture_origin"),
                "cve": case.get("cve"),
                "ghsa": case.get("ghsa"),
                "bug_class": case["bug_class"],
                "size_bytes": len(payload),
                "sha256": digest,
                "source": case["source"],
                "source_url": case["source_url"],
                "affected_range": case["affected_range"],
                "affected_version": case["affected_version"],
                "patched_version": case["patched_version"],
                "patched_commit": case["patched_commit"],
                "expected_profile": case.get("expected_profile"),
                "expected_behavior": case["expected_behavior"],
                "expected_error_code": case["expected_error_code"],
                "cli_args": ["inspect", case["name"]] + case["cli_args"],
            }
        )

    # Prune stale *.gguf files that are no longer part of CASES so the
    # directory always matches the manifest.
    keep = {case["name"] for case in CASES}
    for entry in sorted(os.listdir(NEGATIVE_DIR)):
        if entry.endswith(".gguf") and entry not in keep:
            os.remove(os.path.join(NEGATIVE_DIR, entry))

    manifest = {
        "description": (
            "Negative corpus (roadmap issue #9): synthetic bug-class exemplars "
            "+ provenance-backed advisory regressions; regenerated by "
            "tests/negative_corpus.py - do not hand-edit."
        ),
        "naming_convention": (
            "synthetic-<bug-class>-<slug>.gguf for synthetic class exemplars "
            "(no advisory identity); cve-YYYY-NNNN[-slug].gguf is reserved for "
            "triaged advisory regressions with a verifiable primary source in "
            "source_url."
        ),
        "provenance_rules": (
            "'cases' entries are generated and verified fixtures. "
            "'advisory_placeholders' are manifest-only stubs (fixture null) "
            "and must not be promoted to a cve-* fixture until cve, ghsa, "
            "source_url and a patched reference are triaged from a verifiable "
            "primary source. On promoted cve-* cases, 'fixture_origin' comes "
            "from the closed vocabulary 'exact-poc' (advisory proof of "
            "concept), 'advisory-derived' (advisory mechanism/example shape) "
            "or 'mechanism-equivalent' (equivalent admission property, not a "
            "byte-for-byte upstream reproduction); 'ghsa' carries the GHSA "
            "identifier; 'expected_profile' names the checked profile and "
            "matches the --profile in cli_args. The version/commit fields "
            "'affected_range', 'affected_version', 'patched_version' and "
            "'patched_commit' are nullable: null means not verified / unknown "
            "and is never replaced by a sentinel or an invented value. On "
            "cases without an advisory, null = no advisory provenance; "
            "TRIAGE-PENDING = explicitly unresolved."
        ),
        "upstream_behavior_reference": UPSTREAM_REF,
        "cases": manifest_cases,
        "advisory_placeholders": ADVISORY_PLACEHOLDERS,
    }
    manifest_path = os.path.join(NEGATIVE_DIR, "manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
        f.write("\n")

    return manifest_path


def run_cli(*args):
    cmd = [SAFEGGUF_BIN] + list(args)
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=10)
    return proc.returncode, proc.stdout, proc.stderr


def verify():
    """Assert every corpus fixture is rejected with exit 2 and the expected error_code."""
    failures = []
    for case in CASES:
        path = os.path.join(NEGATIVE_DIR, case["name"])
        if not os.path.exists(path):
            failures.append(f"{case['name']}: fixture missing (run generation first)")
            continue
        args = ["inspect", path] + case["cli_args"]
        try:
            rc, stdout, stderr = run_cli(*args)
        except subprocess.TimeoutExpired:
            failures.append(f"{case['name']}: CLI timed out")
            continue
        if rc != 2:
            failures.append(
                f"{case['name']}: expected exit 2 (REJECT), got {rc}\n"
                f"  stdout: {stdout.strip()}\n  stderr: {stderr.strip()}"
            )
            continue
        if case["expected_error_code"] not in stderr:
            failures.append(
                f"{case['name']}: expected error_code {case['expected_error_code']} "
                f"in stderr, got: {stderr.strip()}"
            )
            continue
        print(f"  REJECT ok [{case['bug_class']}] {case['name']} -> {case['expected_error_code']}")
    return failures


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Negative corpus: synthetic bug-class exemplars + provenance-backed "
            "advisory regressions (issue #9)"
        )
    )
    parser.add_argument("--generate-only", action="store_true", help="generate fixtures + manifest, skip verification")
    parser.add_argument("--verify-only", action="store_true", help="verify existing fixtures without regenerating")
    args = parser.parse_args()

    if not args.verify_only:
        manifest_path = generate()
        n_synthetic = sum(
            1 for c in CASES if c["fixture_type"] == "synthetic-class-exemplar"
        )
        n_advisory = sum(
            1 for c in CASES if c["fixture_type"] == "advisory-regression"
        )
        print(
            f"Generated {n_synthetic} synthetic fixtures + {n_advisory} advisory "
            f"regression fixtures + {len(ADVISORY_PLACEHOLDERS)} advisory "
            f"placeholders (manifest-only, unverified) at {manifest_path}"
        )

    if args.generate_only:
        return 0

    if not os.path.exists(SAFEGGUF_BIN):
        print(f"Error: binary {SAFEGGUF_BIN} does not exist. Run: zig build -Doptimize=ReleaseSafe")
        return 1

    print(f"Verifying {len(CASES)} negative fixtures against {SAFEGGUF_BIN} (expect exit 2 / REJECT)...")
    failures = verify()
    if failures:
        print(f"\nFAILED: {len(failures)} of {len(CASES)} cases:", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1

    classes_covered = sorted({case["bug_class"] for case in CASES})
    missing_classes = [c for c in BUG_CLASSES if c not in classes_covered]
    if missing_classes:
        print(f"\nFAILED: bug classes without a sample: {missing_classes}", file=sys.stderr)
        return 1

    print(f"\nAll {len(CASES)} negative cases rejected (exit 2); bug classes covered: {classes_covered}")
    if ADVISORY_PLACEHOLDERS:
        print(
            "Advisory placeholders still TRIAGE-PENDING (manifest-only, not "
            "fixtures, not verified): "
            + ", ".join(p["id"] for p in ADVISORY_PLACEHOLDERS)
        )
    else:
        promoted = [c for c in CASES if c["fixture_type"] == "advisory-regression"]
        print(
            "No advisory placeholders remain TRIAGE-PENDING; promoted and "
            "verified advisory regressions: " + ", ".join(c["name"] for c in promoted)
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
