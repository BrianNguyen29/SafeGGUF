"""
Negative corpus: synthetic bug-class exemplars + provenance-backed advisory
regressions (roadmap issue #9; provenance split per deep-review F-02).

Two provenance categories - never mix them:

1. Synthetic bug-class exemplars (generated + verified fixtures)
   Name:  synthetic-<bug-class>-<slug>.gguf
   Hand-built malformed inputs that exercise a specific bug class (parse /
   int-overflow / dims / types / alloc / metadata). They are NOT
   reproductions of any specific CVE/advisory and must not carry an advisory
   identity; `source` states the mechanism only.

2. True advisory regressions (promoted after triage; generated + verified)
   Name:  cve-YYYY-NNNN[-slug].gguf
   A fixture may use a cve-* name only once it has a verifiable primary
   source: `cve`, `source_url`, `ghsa` and a patched reference recorded in
   the CASES entry plus the fixture `sha256` (REQUIRED_CVE_FIELDS, enforced
   by _require_triaged_provenance and checked against the generated bytes).
   Promoted cases also carry `fixture_origin` from a closed vocabulary:
   "exact-poc" when the fixture reproduces the advisory's own proof of
   concept, "advisory-derived" when it follows the advisory's
   mechanism/example shape, or "mechanism-equivalent" when SafeGGUF proves
   only the equivalent admission property and does not reproduce the
   upstream allocation byte-for-byte (stated in `source`).
   Version/commit provenance is nullable: `affected_range`,
   `affected_version`, `patched_version` and `patched_commit` stay null
   where no verifiable value was recorded - null means unknown, and no
   range, URL or SHA is ever invented. Advisory entries whose provenance is
   still un-triaged stay in ADVISORY_PLACEHOLDERS as manifest-only records
   (fixture: null, provenance fields TRIAGE-PENDING) and are neither
   generated nor verified. Promote a placeholder to a real cve-* fixture
   only after triage.

Per-case comment convention (the CASES registry is the committed record;
tests/fixtures/negative/manifest.json is the regenerated snapshot):

  fixture_type       synthetic-class-exemplar | advisory-regression.
  fixture_origin     Closed vocabulary on promoted cve-* cases: exact-poc |
                     advisory-derived | mechanism-equivalent; None for
                     synthetic exemplars.
  cve                CVE identifier on promoted cve-* cases (must agree with
                     the fixture name); None for synthetic exemplars.
  ghsa               GHSA advisory identifier on promoted cve-* cases; None
                     for synthetic exemplars.
  source             Mechanism description for synthetic cases; primary
                     advisory reference for triaged advisory cases.
  source_url         Verifiable primary source URL (https://); None for
                     synthetic cases (no advisory exists), TRIAGE-PENDING for
                     placeholders.
  affected_range     Upstream affected version/commit range, or null when the
                     triage did not verify one.
  affected_version   Upstream affected version, or null when unverified.
  patched_version    Upstream version containing the fix, or null when no
                     version was recorded.
  patched_commit     Upstream commit containing the fix, or null when unknown.
                     cve-* cases must record at least one patched reference
                     (patched_version or patched_commit).
  expected_profile   Profile the rejection is asserted under (gguf-spec |
                     llama-cpp); must match the --profile in cli_args.
  sha256             Committed fixture hash on cve-* cases (must match the
                     generated bytes); synthetic cases record it in the
                     manifest only.
  expected_behavior  What SafeGGUF must do: exit 2 (REJECT) and the expected
                     error_code surfaced on stderr / JSON.

All cases and fixtures are behavior-referenced against the pinned upstream in
UPSTREAM_REF (ggml 0.23.0 e91ded11...) and the manifest records that pin
top-level as `upstream_behavior_reference`.

Generation is fully deterministic: fixed little-endian bytes, no randomness,
no timestamps, sorted manifest keys. Re-running overwrites the fixture
directory contents (stale *.gguf files not in CASES are pruned).

Run:  python tests/negative_corpus.py            # generate + verify
      python tests/negative_corpus.py --generate-only
      python tests/negative_corpus.py --verify-only
Verification needs the ReleaseSafe binary at zig-out/bin/safegguf
(zig build -Doptimize=ReleaseSafe). Exit 0 = all cases generated and all
rejections hold; exit 1 = generation or verification failed.
"""

